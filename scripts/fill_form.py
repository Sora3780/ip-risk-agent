def _style_run(run, bold=False, size=9):
    run.font.size = Pt(size)
    run.font.color.rgb = INK
    run.font.bold = bold
    run.font.italic = False
    rpr = run._element.get_or_add_rPr()
    for tag in ("w:rFonts",):
        for el in rpr.findall(f"{{http://schemas.openxmlformats.org/wordprocessingml/2006/main}}rFonts"):
            rpr.remove(el)
    run.font.name = "맑은 고딕"
    # 한글은 eastAsia 글꼴을 따로 지정해야 적용된다
    rf = rpr.get_or_add_rFonts()
    rf.set("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia", "맑은 고딕")


def set_cell(cell, text: str, bold: bool = False, size: int = 9) -> None:
    """셀 내용을 통째로 교체한다. 줄바꿈은 문단으로 나눈다."""
    lines = text.split("\n") if text else [""]
    base = cell.paragraphs[0]
    # 첫 문단만 남기고 나머지 제거
    for p in cell.paragraphs[1:]:
        p._element.getparent().remove(p._element)
    for r in base.runs:
        r._element.getparent().remove(r._element)

    run = base.add_run(lines[0])
    _style_run(run, bold, size)
    for line in lines[1:]:
        newp = copy.deepcopy(base._element)
        base._element.addnext(newp)
        base = cell.paragraphs[-1]
        # deepcopy 로 붙인 문단의 run 을 새 내용으로
        para = [p for p in cell.paragraphs if p._element is newp][0]
        for r in para.runs:
            r._element.getparent().remove(r._element)
        r = para.add_run(line)
        _style_run(r, bold, size)
        base = para


def ensure_rows(table, n: int) -> None:
    """행이 모자라면 마지막 행을 복제해 늘린다. 서식이 유지된다."""
    while len(table.rows) < n:
        table._tbl.append(copy.deepcopy(table.rows[-1]._tr))


def fill_grid(table, rows: list[list[str]], header: bool = True) -> None:
    """머리글 아래를 rows 로 채운다. 부족한 행은 늘리고 남는 행은 지운다."""
    need = len(rows) + (1 if header else 0)
    ensure_rows(table, need)
    while len(table.rows) > need:
        tr = table.rows[-1]._tr
        tr.getparent().remove(tr)
    start = 1 if header else 0
    for r, values in enumerate(rows, start=start):
        cells = table.rows[r].cells
        for c, val in enumerate(values):
            if c < len(cells):
                set_cell(cells[c], val, bold=(c == 0))


def fill_box(table, text: str) -> None:
    """1행 1열 안내 상자에 답변을 넣는다."""
    set_cell(table.rows[0].cells[0], text)


